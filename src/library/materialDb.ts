/**
 * How each process buys its material, which sets the price per kg. Castings
 * buy the alloy as ingot, so their price is the metal's, not the casting's.
 */
export const COST_FORM: Record<ProcessId, CostForm> = {
  fdm: "filament",
  sla: "resin",
  sls: "powder",
  metal_print: "powder",
  cnc_mill: "stock",
  cnc_lathe: "stock",
  injection: "pellets",
  vacuum_cast: "resin",
  die_cast: "ingot",
  sand_cast: "ingot",
  investment_cast: "ingot",
  sheet_metal: "sheet",
  laser_cut: "sheet",
};

/** Price per kg for a material made by a process: the form that process buys, else the nearest form it has. */
export function pricePerKg(m: MaterialRecord, process: ProcessId | undefined): { price: number; form: CostForm } | null {
  const want = process ? COST_FORM[process] : m.printed ? "filament" : "stock";
  const order: CostForm[] = [want, ...(want === "sheet" ? (["stock"] as CostForm[]) : want === "stock" ? (["sheet"] as CostForm[]) : []), "stock", "sheet", "filament", "pellets", "powder", "resin", "ingot"];
  for (const f of order) {
    const p = m.cost[f];
    if (p !== undefined) return { price: p, form: f };
  }
  return null;
}
