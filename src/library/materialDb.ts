// The material database: one record per material, holding everything Kerf
// knows about it. Appearance (library/materials), strength analysis
// (analysis/materials), the brief's service checks (library/materialService),
// the process rules (mfg/materials) and the material advisor (materials/)
// all read from these records, so a part that renders as anodised aluminium
// also weighs, costs, checks and advises as aluminium.
//
// Values are typical for the grade named, rounded to the conservative side.
// FDM plastics carry printed-part strengths, with a separate knock-down for
// strength between layers. Prices are typical small-quantity prices in US
// dollars per kilogram, for comparing materials and budgeting, not quoting.
// A specific product's datasheet wins over all of this.

import type { ProcessId } from "../mfg/types";

export type MaterialCategory = "plastic" | "metal" | "composite" | "other";
export type MaterialFamily = "thermoplastic" | "resin" | "metal" | "composite" | "wood";
export type Rating = "good" | "fair" | "poor";
/** the form a material is bought in for a process, which sets its price */
export type CostForm = "filament" | "powder" | "resin" | "pellets" | "stock" | "sheet" | "ingot";

export interface MechData {
  /** Young's modulus, MPa */
  E: number;
  nu: number;
  /** yield (or 0.2 % proof) strength, MPa; for brittle materials the tensile strength */
  yield: number;
  /** ultimate tensile strength, MPa */
  uts: number;
  /** fatigue strength for about 10⁷ fully reversed cycles, MPa */
  fatigue: number;
  /** elongation at break, % */
  elongation: number;
  /** strength between FDM layers as a fraction of in-plane strength */
  layerFactor: number;
  note?: string;
}

export interface MaterialRecord {
  /** the name written in design files: `material: "PETG"` */
  name: string;
  /** short display name */
  label: string;
  /** the grade the numbers are for, e.g. "Aluminum 6061-T6" */
  grade: string;
  category: MaterialCategory;
  family: MaterialFamily;
  /** g/cm³ */
  density: number;
  /** one line: what it is and when to pick it */
  note: string;

  // ---- look ----
  /** finish ids this material can have (library/materials FINISHES); the first is the default */
  finishes: string[];
  /** typical colour, used when switching to this material */
  color: string;
  /** suggested colours (filament, anodizing, paint) */
  palette: string[];
  /** made on an FDM printer by default (print checks, printed mass, weaker layers in analysis) */
  printed?: boolean;

  // ---- strength ----
  mech: MechData;
  /** allowable bending strain for a snap fit used a few times */
  snapStrain: number;

  // ---- heat ----
  /** highest temperature for long use under light load (about the heat deflection temperature), °C */
  maxC: number;
  /** below this it turns brittle, °C */
  minC: number;
  /** thermal expansion, µm per metre per °C */
  cte: number;
  /** thermal conductivity, W/(m·K) */
  conductivity: number;

  // ---- where it can live ----
  sunlight: Rating;
  /** what goes wrong when wet, if anything */
  wet?: string;
  /** what goes wrong under impact, if anything */
  impact?: string;
  toughness: "brittle" | "fair" | "tough";
  /** how much it deforms under a load held for months */
  creep: "low" | "some" | "high";
  /** share of yield it can hold for years without creeping out of shape (plastics) */
  creepLimit?: number;
  salt: Rating;
  oil: Rating;
  solvents: Rating;
  food: Rating;
  foodNote?: string;
  friction: "low" | "normal" | "high";
  wear: Rating;
  electrical: "conductor" | "insulator";
  /** anodic index in volts (MIL-STD-889): metals and carbon, for galvanic corrosion */
  anodic?: number;

  // ---- making ----
  /** processes this material is commonly made with, most usual first */
  processes: ProcessId[];
  /** injection moulding nominal wall range, mm */
  mouldWall?: [number, number];
  /** minimum inside bend radius as a multiple of sheet thickness */
  bendFactor?: number;
  /** thickest plate a laser cuts cleanly, mm */
  laserMaxT?: number;
  /** sand casting minimum wall: thinner than the first fails, thinner than the second warns, mm (alloys that flow less need more) */
  castWall?: [number, number];
  /** a specific caution for one process (the process checks show it) */
  processNotes?: Partial<Record<ProcessId, string>>;
  /** what printing it takes, for the advisor */
  printNote?: string;

  /** USD per kg in the form each process buys it */
  cost: Partial<Record<CostForm, number>>;
  /** suggested only when a need calls for it (flexible, soft, conducts...), never as an everyday choice */
  special?: string;
}

