function fontTable(): string {
  const L = ["// 5x7 font, ASCII 32..126: five columns per character, bit 0 at the top.", "const uint8_t FONT[] PROGMEM = {"];
  FONT_5X7.forEach((cols, i) => {
    const ch = String.fromCharCode(32 + i);
    const label = ch === " " ? "space" : ch === "\\" ? "backslash" : ch;
    L.push(`  ${cols.map(hex2).join(", ")},  // ${label}`);
  });
  L.push("};");
  return L.join("\n");
}

