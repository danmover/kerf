// Guitar tuner firmware for an Arduino Nano (ATmega328P) behind a practice
// amp's front panel: it always shows the note being played and how many cents
// sharp or flat it is on a 128x64 SSD1306 OLED, with no button needed to tune.
//
// The sketch samples the guitar signal with the free-running ADC (9615 Hz,
// 1024 samples per buffer), finds the period with a YIN difference function
// for the coarse value and refines it at a large multiple of the period for
// sub-cent precision, all in 8-bit samples and integer sums so a buffer takes
// well under 120 ms on the 16 MHz AVR. A button changes the reference pitch
// and calibrates the clock (ceramic resonators are up to 0.5 % off). It uses
// only the Arduino core plus the bundled Wire and EEPROM libraries.

import type { GenFile } from "./common";

export interface TunerOptions {
  designName: string;
  /** analog input for the guitar signal: "A0".."A7" */
  adcPin: string;
  /** Arduino pin number of the button, as text: "2" (default). "A0".."A3" also work. */
  buttonPin?: string;
  /** 7-bit I2C address of the SSD1306 OLED, 0x3C (default) or 0x3D */
  oledAddr?: number;
  /** reference pitch for A4 until the user changes it with the button (440 default) */
  refHz?: number;
}

export interface TunerFirmware {
  files: GenFile[];
  warnings: string[];
  pinTable: { signal: string; pin: string; wire: string }[];
}

/** The reference pitches a short press steps through, in order. */
const REFERENCES = [440, 441, 442, 443, 444, 445, 432, 435, 438, 439];

/** Arduino needs the sketch folder and the .ino to share a name made of letters, digits and underscores. */
function sketchName(design: string): string {
  const n = design.replace(/[^A-Za-z0-9]+/g, "_").replace(/^_+|_+$/g, "").slice(0, 60);
  return n || "tuner";
}

/** Text that is safe inside a // comment (no line breaks, no line-continuing backslash). */
const commentText = (s: string) => s.replace(/[\r\n\\]+/g, " ").trim();

const hex2 = (n: number) => `0x${n.toString(16).toUpperCase().padStart(2, "0")}`;

export function tunerSketch(o: TunerOptions): TunerFirmware {
  const warnings: string[] = [];
  const name = sketchName(o.designName);
  const design = commentText(o.designName) || name;

  // ---- the signal input ----
  let adc = (o.adcPin ?? "").trim().toUpperCase();
  if (!/^A[0-7]$/.test(adc)) {
    warnings.push(`The guitar signal must go to an analog input A0..A7 (got "${o.adcPin}"): the sketch uses A0.`);
    adc = "A0";
  }
  const adcChannel = Number(adc.slice(1));

  // ---- the button ----
  const button = buttonPinFor(o.buttonPin ?? "2", adc, warnings);

  // ---- the display ----
  let oled = o.oledAddr ?? 0x3c;
  if (!Number.isInteger(oled) || oled < 0x08 || oled > 0x77) {
    warnings.push(`OLED address ${o.oledAddr} is not a 7-bit I2C address: the sketch uses 0x3C.`);
    oled = 0x3c;
  } else if (oled !== 0x3c && oled !== 0x3d) {
    warnings.push(`SSD1306 modules answer at 0x3C or 0x3D; ${hex2(oled)} is unusual, so check the module's address jumper.`);
  }

  // ---- the reference pitch ----
  let refIndex = REFERENCES.indexOf(o.refHz ?? 440);
  if (refIndex < 0) {
    const want = Number(o.refHz);
    refIndex = Number.isFinite(want) ? REFERENCES.reduce((best, r, i) => (Math.abs(r - want) < Math.abs(REFERENCES[best] - want) ? i : best), 0) : 0;
    warnings.push(`The reference must be one of ${REFERENCES.join(", ")} Hz (the button steps through them): the sketch starts at ${REFERENCES[refIndex]} Hz.`);
  }

  const pinTable: TunerFirmware["pinTable"] = [
    { signal: "GUITAR_IN", pin: adc, wire: "op-amp stage output, AC-coupled into the 100k/100k divider (idles at 2.5 V)" },
    { signal: "BUTTON", pin: button.label, wire: "momentary button to GND (internal pull-up)" },
    { signal: "OLED_SDA", pin: "A4", wire: "SSD1306 SDA" },
    { signal: "OLED_SCL", pin: "A5", wire: "SSD1306 SCL" },
    { signal: "OLED_VCC", pin: "5V", wire: "SSD1306 VCC (the module regulates to 3.3 V)" },
    { signal: "GND", pin: "GND", wire: "SSD1306 GND, button, signal ground" },
  ];

  const head = [
    `// ${name}: automatic chromatic tuner for the amp's front panel.`,
    `// Generated by Kerf for "${design}". Board: Arduino Nano (ATmega328P, 16 MHz).`,
    "//",
    "// Play a note and the OLED shows its name, how many cents sharp (+) or flat (-)",
    "// it is and a needle; the needle is centred and the note box lights up when",
    "// you are within 2 cents. Nothing to press. Every reading is also printed on",
    "// the Serial Monitor at 115200 baud, for example: E2 -3.4c 82.25Hz",
    "//",
    "// Button: short press steps the A4 reference through 440..445, 432, 435, 438,",
    "// 439 Hz. Hold it 3 s while an A (any octave, tuned with a trusted tuner) rings",
    "// to calibrate the board's clock. Hold it while powering up to undo that.",
    "// Both settings are kept in EEPROM.",
    "//",
    "// How the pitch is found (all in loop(), between captures):",
    "//  1. The ADC runs free at 16 MHz / 128 / 13 = 9615.4 samples per second and",
    "//     its interrupt stores 1024 8-bit samples (106 ms) in a buffer.",
    "//  2. Gate: quiet buffers are skipped. If a pluck starts inside the buffer, only",
    "//     what follows its attack is used; if that is under 90 ms the buffer is",
    "//     dropped at once and the next one, all after the pluck, is used instead.",
    "//  3. Coarse period: YIN's normalised difference function on every second",
    "//     sample, lags for 57..800 Hz. The first dip that is deep, or nearly as deep",
    "//     as the deepest, is the period, which avoids octave errors from strong",
    "//     harmonics.",
    "//  4. The buffer is smoothed (a moving average of a sixth of the period, twice):",
    "//     the high partials of a stiff string run sharp and would pull the pitch up.",
    "//  5. Fine period: the full-rate difference function around one period, then",
    "//     around a multiple of it two thirds of the buffer long (up to ~45 periods",
    "//     for high notes). A parabola through the lowest three points places the",
    "//     dip to a fraction of a sample; dividing by the multiple makes the period",
    "//     that many times more precise.",
    "//  6. While a note rings, the buffers' periods are averaged, each weighted by",
    "//     how precise it is; a new pluck or a change of more than 4 cents starts over.",
    "//  At most about 50 ms of AVR time per buffer: a reading about 7 times a second,",
    "//  the first within 0.3 s of the pluck.",
    "",
    "#include <Arduino.h>",
    "#include <Wire.h>",
    "#include <EEPROM.h>",
    "#include <avr/io.h>",
    "#include <avr/interrupt.h>",
    "#include <avr/pgmspace.h>",
    "",
    "// ---------------- wiring (from the design) ----------------",
    `const uint8_t SIGNAL_PIN = ${adc};       // guitar signal from the op-amp stage, idles at 2.5 V`,
    `const uint8_t BUTTON_PIN = ${button.code};${" ".repeat(Math.max(1, 7 - button.code.length))}// momentary button to GND; the internal pull-up holds it high`,
    `const uint8_t OLED_ADDR = ${hex2(oled)};     // SSD1306 128x64 OLED on the I2C pins: A4 = SDA, A5 = SCL`,
    `const uint8_t DEFAULT_REF = ${refIndex};       // A4 = ${REFERENCES[refIndex]} Hz until the button changes it (index in REF_HZ)`,
    "",
  ];
  const font = fontTable();
  const ino = [...head, BODY_SETTINGS.trim(), "", font, "", BODY_CODE.trim(), ""].join("\n");

  const readme = tunerReadme({ name, design, adc, button: button.label, oled, ref: REFERENCES[refIndex], warnings, pinTable, adcChannel });
  return {
    files: [
      { path: `${name}/${name}.ino`, content: ino },
      { path: `${name}/README.md`, content: readme },
    ],
    warnings,
    pinTable,
  };
}

/** The button's C expression and the label for the pin table, checked against the Nano's pins. */
function buttonPinFor(raw: string, adc: string, warnings: string[]): { code: string; label: string } {
  const fallback = { code: "2", label: "D2" };
  const t = String(raw).trim().toUpperCase().replace(/^D(?=\d)/, "");
  let code: string, label: string, analog: number | undefined;
  if (/^\d+$/.test(t)) {
    const n = Number(t);
    if (n >= 14 && n <= 21) {
      analog = n - 14;
      code = `A${analog}`;
      label = code;
    } else {
      code = String(n);
      label = `D${n}`;
    }
    if (n > 21) {
      warnings.push(`The Nano has no pin ${raw} for the button: the sketch uses D2.`);
      return fallback;
    }
  } else if (/^A[0-7]$/.test(t)) {
    analog = Number(t.slice(1));
    code = t;
    label = t;
  } else {
    warnings.push(`Button pin "${raw}" is not an Arduino pin number: the sketch uses D2.`);
    return fallback;
  }
  const clash = (why: string) => {
    warnings.push(`The button cannot use ${label}: ${why}. The sketch uses D2.`);
    return fallback;
  };
  if (code === "0" || code === "1") return clash("D0 and D1 carry Serial (USB)");
  if (analog === 4 || analog === 5) return clash("A4 and A5 are the OLED's I2C pins");
  if (analog === 6 || analog === 7) return clash("A6 and A7 on the Nano are analog-only, with no digital input or pull-up");
  if (label === adc) return clash("it is the guitar signal input");
  if (code === "13") warnings.push("D13 has the on-board LED, which can pull the button input low; another pin is more reliable.");
  return { code, label };
}

