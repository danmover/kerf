// Writes src/analysis/fe/ebe.gen.ts: the element-by-element product y += s·K·x
// for 8-node hex elements, fully unrolled. Keeping the 24 displacements in
// locals and indexing K with constants runs about 3.5× faster in V8 than the
// equivalent loops, and the multigrid solve spends most of its time here.
// Run: node scripts/gen-ebe-kernel.mjs
import { writeFileSync } from "node:fs";

const offs = ["0", "3", "3 * NX", "3 * NX + 3", "3 * NXY", "3 * NXY + 3", "3 * (NXY + NX)", "3 * (NXY + NX) + 3"];
const out = [];
out.push("// Generated by scripts/gen-ebe-kernel.mjs; do not edit by hand.");
out.push("/* eslint-disable */");
out.push("");
out.push("/**");
out.push(" * y += stiff[e] · K · x over every element e whose (0,0,0) corner is node act[e],");
out.push(" * on a grid with NX nodes along x and NX·NY per layer. K is the 24×24 element");
out.push(" * matrix (row-major, corner a = dx + 2dy + 4dz, xyz per corner). y is not cleared.");
out.push(" */");
out.push("export function ebeProduct(K: Float64Array, act: Int32Array, stiff: Float64Array, NX: number, NXY: number, x: Float64Array, y: Float64Array): void {");
out.push("  " + "const " + offs.map((o, a) => `o${a} = ${o}`).join(", ") + ";");
out.push("  for (let e = 0; e < act.length; e++) {");
out.push("    const d = 3 * act[e];");
out.push("    const s = stiff[e];");
for (let a = 0; a < 8; a++) for (let c = 0; c < 3; c++) out.push(`    const u${3 * a + c} = x[d + o${a} + ${c}];`);
for (let a = 0; a < 8; a++)
  for (let c = 0; c < 3; c++) {
    const r = 3 * a + c;
    const terms = Array.from({ length: 24 }, (_, j) => `K[${r * 24 + j}] * u${j}`).join(" + ");
    out.push(`    y[d + o${a} + ${c}] += s * (${terms});`);
  }
out.push("  }");
out.push("}");
writeFileSync(new URL("../src/analysis/fe/ebe.gen.ts", import.meta.url), out.join("\n") + "\n");
